    public static String formatUserPrompt(String userMessages) {
        return "**用户输入：**\n" + userMessages;
    }

    public static String formatResourceUserPrompt(String agentFactorInfo, String resource) {
        return "**Agent基础要素规划：**\n" + agentFactorInfo + "\n**可用资源库：**\n" + resource;
    }

    public static String formatGenerateUserPrompt(String userMessage, String agentConfigInfo, String agentResourceInfo) {
        return "**用户消息：**\n" + userMessage + "\n**Agent配置信息：**\n" + agentConfigInfo + "\n**Agent资源信息：**\n" + agentResourceInfo;
    }

    public static String formatUserIntentionPrompt(String query, String agentConfigInfo) {
        return "**查询：**\n" + query + "\n**Agent配置信息：**\n" + agentConfigInfo;
    }
