package com.openjiuwen.agent_evolving.dataset;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.openjiuwen.core.common.exception.ValidationError;
import com.openjiuwen.core.foundation.tool.schema.ToolInfo;
import org.junit.jupiter.api.Test;

import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Tests for Case and EvaluatedCase data models.
 *
 * <p>Mirrors Python's {@code tests.unit_tests.agent_evolving.dataset.test_case}.</p>
 */
class CaseTest {

    private static final ObjectMapper OBJECT_MAPPER = new ObjectMapper();

    @Test
    void caseSupportsMinimalCreationAndGeneratedCaseId() {
        Case caseData = new Case(Map.of("query", "test"), Map.of("answer", "expected"));

        assertEquals(Map.of("query", "test"), caseData.getInputs());
        assertEquals(Map.of("answer", "expected"), caseData.getLabel());
        assertNotNull(caseData.getCaseId());
        assertEquals(32, caseData.getCaseId().length());
    }

    @Test
    void caseSupportsCustomCaseId() {
        Case caseData = new Case(Map.of("query", "test"), Map.of("answer", "expected"), "custom_id");

        assertEquals("custom_id", caseData.getCaseId());
    }

    @Test
    void caseIdAutoGenerated() {
        Case caseData = new Case(Map.of("query", "test"), Map.of("answer", "expected"));

        assertEquals(32, caseData.getCaseId().length());
    }

    @Test
    void caseRejectsEmptyInputsOrLabels() {
        assertThrows(ValidationError.class, () -> new Case(Map.of(), Map.of("answer", "expected")));
        assertThrows(ValidationError.class, () -> new Case(Map.of("query", "test"), Map.of()));
    }

    @Test
    void caseInputsValidation() {
        assertThrows(ValidationError.class, () -> new Case(Map.of(), Map.of("answer", "expected")));
    }

    @Test
    void caseLabelValidation() {
        assertThrows(ValidationError.class, () -> new Case(Map.of("query", "test"), Map.of()));
    }

    @Test
    void caseToolsOptional() {
        Case caseData = new Case(Map.of("query", "test"), Map.of("answer", "expected"));

        assertNull(caseData.getTools());
    }

    @Test
    void caseSerialization() {
        Case caseData = new Case(Map.of("q", "test"), Map.of("answer", "expected"), "test_id");

        Map<?, ?> data = OBJECT_MAPPER.convertValue(caseData, Map.class);

        assertEquals(Map.of("q", "test"), data.get("inputs"));
        assertEquals(Map.of("answer", "expected"), data.get("label"));
        assertEquals("test_id", data.get("caseId"));
    }

    @Test
    void caseJsonSerialization() throws Exception {
        Case caseData = new Case(Map.of("q", "test"), Map.of("answer", "expected"));

        String json = OBJECT_MAPPER.writeValueAsString(caseData);

        assertTrue(json.contains("test"));
    }

    @Test
    void evaluatedCaseFullCreation() {
        Case caseData = new Case(Map.of("query", "test"), Map.of("answer", "expected"));
        EvaluatedCase ec = new EvaluatedCase(caseData, Map.of("output", "result"), 0.85, "mostly correct");

        assertSame(caseData, ec.getCase());
        assertEquals(Map.of("output", "result"), ec.getAnswer());
        assertEquals(0.85, ec.getScore());
        assertEquals("mostly correct", ec.getReason());
        assertNull(ec.getPerMetric());
    }

    @Test
    void evaluatedCaseDefaultValues() {
        Case caseData = new Case(Map.of("query", "test"), Map.of("answer", "expected"));
        EvaluatedCase ec = new EvaluatedCase(caseData, null);

        assertNull(ec.getAnswer());
        assertEquals(0.0, ec.getScore());
        assertEquals("", ec.getReason());
        assertNull(ec.getPerMetric());
    }

    @Test
    void evaluatedCaseClampsScoreAndDelegatesProperties() {
        Case caseData = new Case(Map.of("query", "test"), Map.of("answer", "expected"), "case_1");
        EvaluatedCase evaluated = EvaluatedCase.builder()
                .caseData(caseData)
                .score(1.5)
                .reason("good")
                .build();

        assertEquals(1.0, evaluated.getScore());
        assertEquals(Map.of("query", "test"), evaluated.getInputs());
        assertEquals(Map.of("answer", "expected"), evaluated.getLabel());
        assertEquals("case_1", evaluated.getCaseId());
        assertEquals("good", evaluated.getReason());
    }

    @Test
    void evaluatedCaseScoreLowerBound() {
        Case caseData = new Case(Map.of("query", "test"), Map.of("answer", "expected"));
        EvaluatedCase evaluated = new EvaluatedCase(caseData, null, -0.5, "", null);

        assertEquals(0.0, evaluated.getScore());
    }

    @Test
    void evaluatedCasePropertyDelegation() {
        Case caseData = new Case(Map.of("q", "test"), Map.of("a", "ans"), "id123");
        EvaluatedCase ec = new EvaluatedCase(caseData, null);

        assertEquals(Map.of("q", "test"), ec.getInputs());
        assertEquals(Map.of("a", "ans"), ec.getLabel());
        assertEquals("id123", ec.getCaseId());
    }

    @Test
    void evaluatedCaseToolsDelegation() {
        ToolInfo tool = ToolInfo.builder().name("test_tool").description("A test tool").build();
        Case caseData = new Case(Map.of("query", "test"), Map.of("answer", "expected"), List.of(tool), "case_tool");
        EvaluatedCase ec = new EvaluatedCase(caseData, null);

        assertEquals(List.of(tool), ec.getTools());
    }

    @Test
    void evaluatedCasePerMetricStorage() {
        Case caseData = new Case(Map.of("query", "test"), Map.of("answer", "expected"));
        EvaluatedCase ec = new EvaluatedCase(caseData, null, 0.0, "", Map.of("exact_match", 1.0, "llm_judge", 0.8));

        assertEquals(Map.of("exact_match", 1.0, "llm_judge", 0.8), ec.getPerMetric());
    }

    @Test
    void evaluatedCaseModelDumpIncludesAllFields() {
        Case caseData = new Case(Map.of("query", "test"), Map.of("answer", "expected"), "id1");
        EvaluatedCase ec = new EvaluatedCase(caseData, Map.of("out", "x"), 0.9, "good", Map.of("metric", 0.9));

        Map<?, ?> data = OBJECT_MAPPER.convertValue(ec, Map.class);

        assertEquals(0.9, data.get("score"));
        assertEquals(Map.of("out", "x"), data.get("answer"));
        assertEquals("good", data.get("reason"));
        assertEquals(Map.of("metric", 0.9), data.get("perMetric"));
    }
}
