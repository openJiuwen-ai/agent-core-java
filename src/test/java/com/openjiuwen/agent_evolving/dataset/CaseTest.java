package com.openjiuwen.agent_evolving.dataset;

import com.openjiuwen.core.foundation.tool.schema.ToolInfo;
import org.junit.jupiter.api.Test;

import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertSame;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Tests for Case and EvaluatedCase data models.
 *
 * <p>Mirrors Python's {@code TestCase} and {@code TestEvaluatedCase} in
 * {@code tests/unit_tests/agent_evolving/dataset/test_case.py}.</p>
 *
 * <p>Also exercises Java classes that mirror Python's {@code Case} and {@code EvaluatedCase} in
 * {@code openjiuwen/agent_evolving/dataset/case.py}.</p>
 */
class CaseTest {

    @Test
    void caseMinimalCreation() {
        Case sample = makeCase();

        assertEquals(Map.of("query", "test"), sample.getInputs());
        assertEquals(Map.of("answer", "expected"), sample.getLabel());
        assertNotNull(sample.getCaseId());
        assertNull(sample.getTools());
    }

    @Test
    void caseIdAutoGenerated() {
        Case sample = makeCase();

        assertEquals(32, sample.getCaseId().length());
    }

    @Test
    void caseIdCustom() {
        Case sample = makeCase(null, null, null, "custom_id");

        assertEquals("custom_id", sample.getCaseId());
    }

    @Test
    void toolsOptional() {
        Case sample = makeCase();

        assertNull(sample.getTools());
    }

    @Test
    void inputsValidation() {
        assertThrows(IllegalArgumentException.class, () -> new Case(Map.of(), Map.of("a", "b")));
    }

    @Test
    void labelValidation() {
        assertThrows(IllegalArgumentException.class, () -> new Case(Map.of("q", "a"), Map.of()));
    }

    @Test
    void caseSerialization() {
        Case sample = makeCase(Map.of("q", "test"), null, null, "test_id");
        Map<String, Object> data = sample.modelDump();

        assertEquals(Map.of("q", "test"), data.get("inputs"));
        assertEquals(Map.of("answer", "expected"), data.get("label"));
        assertEquals("test_id", data.get("case_id"));
    }

    @Test
    void caseJsonSerialization() {
        Case sample = makeCase(Map.of("q", "test"), null, null, null);

        assertTrue(sample.modelDumpJson().contains("test"));
    }

    @Test
    void evaluatedCaseFullCreation() {
        Case sample = makeCase();
        EvaluatedCase evaluated = new EvaluatedCase(
                sample,
                Map.of("output", "result"),
                0.85d,
                "mostly correct",
                null
        );

        assertSame(sample, evaluated.getCase());
        assertEquals(Map.of("output", "result"), evaluated.getAnswer());
        assertEquals(0.85d, evaluated.getScore(), 1.0e-9);
        assertEquals("mostly correct", evaluated.getReason());
        assertNull(evaluated.getPerMetric());
    }

    @Test
    void evaluatedCaseDefaultValues() {
        EvaluatedCase evaluated = new EvaluatedCase(makeCase());

        assertNull(evaluated.getAnswer());
        assertEquals(0.0d, evaluated.getScore(), 1.0e-9);
        assertEquals("", evaluated.getReason());
        assertNull(evaluated.getPerMetric());
    }

    @Test
    void scoreUpperBound() {
        EvaluatedCase evaluated = new EvaluatedCase(makeCase(), null, 1.5d, "", null);

        assertEquals(1.0d, evaluated.getScore(), 1.0e-9);
    }

    @Test
    void scoreLowerBound() {
        EvaluatedCase evaluated = new EvaluatedCase(makeCase(), null, -0.5d, "", null);

        assertEquals(0.0d, evaluated.getScore(), 1.0e-9);
    }

    @Test
    void propertyDelegation() {
        Case sample = makeCase(Map.of("q", "test"), Map.of("a", "ans"), null, "id123");
        EvaluatedCase evaluated = new EvaluatedCase(sample);

        assertEquals(Map.of("q", "test"), evaluated.getInputs());
        assertEquals(Map.of("a", "ans"), evaluated.getLabel());
        assertEquals("id123", evaluated.getCaseId());
    }

    @Test
    void toolsDelegation() {
        ToolInfo tool = ToolInfo.builder().name("test_tool").description("A test tool").build();
        Case sample = makeCase(null, null, List.of(tool), null);
        EvaluatedCase evaluated = new EvaluatedCase(sample);

        assertEquals(List.of(tool), evaluated.getTools());
    }

    @Test
    void perMetricStorage() {
        EvaluatedCase evaluated = new EvaluatedCase(
                makeCase(),
                null,
                0.0d,
                "",
                Map.of("exact_match", 1.0d, "llm_judge", 0.8d)
        );

        assertEquals(Map.of("exact_match", 1.0d, "llm_judge", 0.8d), evaluated.getPerMetric());
    }

    @Test
    void evaluatedModelDumpIncludesAllFields() {
        Case sample = makeCase(null, null, null, "id1");
        EvaluatedCase evaluated = new EvaluatedCase(
                sample,
                Map.of("out", "x"),
                0.9d,
                "good",
                Map.of("metric", 0.9d)
        );
        Map<String, Object> data = evaluated.modelDump();

        assertEquals(0.9d, (Double) data.get("score"), 1.0e-9);
        assertEquals(Map.of("out", "x"), data.get("answer"));
        assertEquals("good", data.get("reason"));
        assertEquals(Map.of("metric", 0.9d), data.get("per_metric"));
    }

    @Test
    void modelDumpJsonIncludesSnakeCaseCaseId() {
        Case sample = makeCase(null, null, null, "id1");

        assertTrue(sample.modelDumpJson().contains("case_id"));
        assertFalse(sample.modelDumpJson().contains("caseId"));
    }

    private static Case makeCase() {
        return makeCase(null, null, null, null);
    }

    private static Case makeCase(
            Map<String, Object> inputs,
            Map<String, Object> label,
            List<ToolInfo> tools,
            String caseId
    ) {
        return new Case(
                inputs == null ? Map.of("query", "test") : inputs,
                label == null ? Map.of("answer", "expected") : label,
                tools,
                caseId
        );
    }
}
