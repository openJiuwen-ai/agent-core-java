package com.openjiuwen.core.foundation.llm.multimodal;

import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Normalized multimodal content block of the agent entry contract.
 *
 * <p>Blocks are the vendor-neutral internal representation produced by
 * {@link MultimodalContentNormalizer}. They are transient: the agent entry
 * resolves image sources and converts blocks into Chat Completions content
 * parts before they are stored on a message, so blocks themselves never
 * enter message content or persistence.</p>
 *
 * @since 0.1.17
 */
public sealed interface ContentBlock {
    /**
     * Return the block identifier, generated by the normalizer when absent
     * and stable within one request.
     *
     * @return block id, never {@code null}
     */
    String id();

    /**
     * Return the recognized block type.
     *
     * @return content block type, never {@code null}
     */
    ContentBlockType type();

    /**
     * Plain text block.
     *
     * @param id block id, never {@code null}
     * @param text original text, never {@code null}
     */
    record Text(String id, String text) implements ContentBlock {

        @Override
        public ContentBlockType type() {
            return ContentBlockType.TEXT;
        }
    }

    /**
     * Image block carrying exactly one explicit source.
     *
     * @param id block id, never {@code null}
     * @param source explicit image source, never {@code null}
     * @param mediaType caller-declared MIME type; may be {@code null}
     * @param filename original file name; may be {@code null}
     * @param description caller-provided caption; may be {@code null}
     * @param provenance origin metadata kept in framework context; never {@code null}
     */
    record Image(String id, ImageSource source, String mediaType, String filename,
            String description, Map<String, Object> provenance) implements ContentBlock {

        /**
         * Create an image block with a defensive immutable provenance copy.
         *
         * @param id block id
         * @param source explicit image source
         * @param mediaType declared MIME type; may be {@code null}
         * @param filename original file name; may be {@code null}
         * @param description caption; may be {@code null}
         * @param provenance origin metadata; {@code null} becomes an empty map
         */
        public Image {
            provenance = copyProvenance(provenance);
        }

        @Override
        public ContentBlockType type() {
            return ContentBlockType.IMAGE;
        }
    }

    /**
     * Reserved video block. The enumeration slot exists so future video
     * support does not change the contract; this release rejects video
     * blocks at the agent entry.
     *
     * @param id block id, never {@code null}
     * @param source explicit material source, never {@code null}
     * @param mediaType caller-declared MIME type; may be {@code null}
     * @param filename original file name; may be {@code null}
     * @param description caller-provided caption; may be {@code null}
     * @param provenance origin metadata kept in framework context; never {@code null}
     */
    record Video(String id, ImageSource source, String mediaType, String filename,
            String description, Map<String, Object> provenance) implements ContentBlock {

        /**
         * Create a video block with a defensive immutable provenance copy.
         *
         * @param id block id
         * @param source explicit material source
         * @param mediaType declared MIME type; may be {@code null}
         * @param filename original file name; may be {@code null}
         * @param description caption; may be {@code null}
         * @param provenance origin metadata; {@code null} becomes an empty map
         */
        public Video {
            provenance = copyProvenance(provenance);
        }

        @Override
        public ContentBlockType type() {
            return ContentBlockType.VIDEO;
        }
    }

    /**
     * Non-image attachment reference block. A file block whose material
     * resolves to an image MIME type may be converted into an image; without
     * an available processing chain the entry fails explicitly with
     * {@code FILE_PROCESSING_REQUIRED} instead of sending only the name.
     *
     * @param id block id, never {@code null}
     * @param source explicit material source, never {@code null}
     * @param mediaType caller-declared MIME type; may be {@code null}
     * @param filename original file name; may be {@code null}
     * @param description caller-provided caption; may be {@code null}
     * @param provenance origin metadata kept in framework context; never {@code null}
     */
    record FileRef(String id, ImageSource source, String mediaType, String filename,
            String description, Map<String, Object> provenance) implements ContentBlock {

        /**
         * Create a file block with a defensive immutable provenance copy.
         *
         * @param id block id
         * @param source explicit material source
         * @param mediaType declared MIME type; may be {@code null}
         * @param filename original file name; may be {@code null}
         * @param description caption; may be {@code null}
         * @param provenance origin metadata; {@code null} becomes an empty map
         */
        public FileRef {
            provenance = copyProvenance(provenance);
        }

        @Override
        public ContentBlockType type() {
            return ContentBlockType.FILE;
        }
    }

    /**
     * Tool result block. Valid only on the tool-result channel contract; the
     * agent entry rejects it because user input cannot carry tool identity.
     *
     * @param id block id, never {@code null}
     * @param toolCallId bound tool call id, never {@code null}
     * @param toolName bound tool name, never {@code null}
     * @param status one of {@code success}, {@code partial}, {@code failed}
     * @param items ordered per-item results; never {@code null}
     */
    record ToolResult(String id, String toolCallId, String toolName, String status,
            List<Object> items) implements ContentBlock {

        /**
         * Create a tool result block with a defensive immutable items copy.
         *
         * @param id block id
         * @param toolCallId bound tool call id
         * @param toolName bound tool name
         * @param status item status summary
         * @param items ordered per-item results; {@code null} becomes an empty list
         */
        public ToolResult {
            items = items == null
                    ? List.of()
                    : Collections.unmodifiableList(new ArrayList<>(items));
        }

        @Override
        public ContentBlockType type() {
            return ContentBlockType.TOOL_RESULT;
        }
    }

    /**
     * Copy provenance into an immutable order-preserving map.
     *
     * @param provenance origin metadata; may be {@code null}
     * @return immutable copy, never {@code null}
     */
    private static Map<String, Object> copyProvenance(Map<String, Object> provenance) {
        return provenance == null
                ? Collections.emptyMap()
                : Collections.unmodifiableMap(new LinkedHashMap<>(provenance));
    }
}
